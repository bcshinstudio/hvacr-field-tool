import assert from 'node:assert/strict';
import { resolveHighSidePressure, resolveEvaporatingPressure } from '../src/diagnostics/pressure_locations.js';
import { calculateDiagnosticState } from '../src/diagnostics/diagnostic_engine.js';
const sat = (p) => p / 10;
const base = { references: {}, saturationTemperatureFromPressure: sat };
const high = resolveHighSidePressure({ compressorDischargePressure: 312 });
assert.equal(high.pressure, 312);
assert.equal(high.location, 'Compressor Discharge');
assert.equal(high.approximate, true);
assert.equal(resolveHighSidePressure({ compressorDischargePressure: 312, kingValvePressure: 307, condenserOutletPressure: 310 }).pressure, 310);
assert.equal(resolveHighSidePressure({ compressorDischargePressure: 312, kingValvePressure: 307 }).spreadPsig, 5);
assert.equal(resolveHighSidePressure({}).pressure, null);
assert.equal(resolveEvaporatingPressure({ compressorSuctionPressure: 77 }).approximate, true);
const dischargeOnly = calculateDiagnosticState({ ...base, measurements: { compressorDischargePressure: 312, condenserOutletTemperature: 110 } });
assert.equal(dischargeOnly.condenserSat, 31.2);
assert.equal(dischargeOnly.condenserSatApproximate, true);
assert.equal(dischargeOnly.subcooling, null, 'remote pressure must not silently create subcooling');
const evapFallback = calculateDiagnosticState({ ...base, measurements: { compressorSuctionPressure: 77, evaporatorOutletTemperature: 45 } });
assert.equal(evapFallback.evaporatorSat, 7.7);
assert.equal(evapFallback.evaporatorSuperheat, null, 'remote suction pressure must not silently create evaporator superheat');
const matched = calculateDiagnosticState({ ...base, measurements: { evaporatorOutletPressure: 77, evaporatorOutletTemperature: 45, condenserOutletPressure: 312, condenserOutletTemperature: 110 } });
assert.equal(matched.evaporatorSuperheat, 37.3);
assert.equal(matched.subcooling, -78.8);
console.log('PRESSURE LOCATION FALLBACK: 12 assertions PASS');
