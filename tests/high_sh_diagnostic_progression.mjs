import assert from 'node:assert/strict';
import fs from 'node:fs';
import { evaluateKnowledge } from '../src/knowledge/knowledge_engine.js';
const read = (name) => JSON.parse(fs.readFileSync(new URL(`../data/knowledge/core/${name}.json`,import.meta.url),'utf8')).items;
const knowledge = { rules:read('evidence_rules'),relationships:read('relationships'),checks:read('checks'),discriminators:read('discriminators')};
const evaluate = facts => evaluateKnowledge({...knowledge,facts});
const onlyHighSH=evaluate(['FACT_EVAP_SH_HIGH']);
assert(onlyHighSH.conditions.some(c=>c.id==='COND_EVAP_STARVED'));
assert(onlyHighSH.possible.some(c=>c.candidate==='CAUSE_LOW_REFRIGERANT_CHARGE'));
assert(!onlyHighSH.diagnoses.some(c=>c.candidate==='CAUSE_LOW_REFRIGERANT_CHARGE'));
assert.equal(onlyHighSH.nextCheck,'CHECK_MEASURE_SC');
const measured=evaluate(['FACT_EVAP_SH_HIGH','FACT_SUBCOOLING_MEASURED']);
assert.notEqual(measured.nextCheck,'CHECK_MEASURE_SC','Do not request a measurement already obtained');
assert(measured.nextCheck,'Continue discriminating if only measured, not characterized');
const lowSC=evaluate(['FACT_EVAP_SH_HIGH','FACT_SUBCOOLING_LOW']);
assert(lowSC.diagnoses.some(c=>c.candidate==='CAUSE_LOW_REFRIGERANT_CHARGE'));
assert.equal(lowSC.nextCheck,'CHECK_LEAK','Investigate source of suspected charge loss before concluding');
const leakEvidence=evaluate(['FACT_EVAP_SH_HIGH','FACT_SUBCOOLING_LOW','FACT_OIL_STAIN_OR_LEAK_EVIDENCE']);
assert(leakEvidence.diagnoses.some(c=>c.candidate==='CAUSE_LOW_REFRIGERANT_CHARGE'));
assert.notEqual(leakEvidence.nextCheck,'CHECK_MEASURE_SC');
console.log('PASS: high-SH suspect → useful discrimination → charge-loss investigation');
