import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const phase4File='docs/knowledge_coverage_phase4.json';
if(!fs.existsSync(path.join(root,phase4File))){console.error('Run node tools\\knowledge_coverage_phase4.mjs first.');process.exit(2);}
const phase4=read(phase4File);
const suites=[
 {id:'WIC_STARVATION',runner:'tests/wic_starvation_differential.mjs'},
 {id:'REACH_IN_SAFETY',runner:'tests/reach_in_brain_safety.mjs'},
 {id:'BRAIN_CONDITION',runner:'tests/brain_2_0_condition_preservation.mjs'},
 {id:'RESIDENTIAL_AC_DEEP',runner:'tests/residential_ac_deep/residential_ac_deep_runner.mjs',
  dataset:'tests/residential_ac_deep/residential_ac_deep_cases.json',report:'tests/residential_ac_deep/residential_ac_deep_report.json'}
];
const runs=[];
for(const s of suites){
 const p=spawnSync(process.execPath,[path.join(root,s.runner)],{cwd:root,encoding:'utf8',maxBuffer:8*1024*1024});
 runs.push({id:s.id,runner:s.runner,status:p.status===0&&!p.error?'PASS':'FAIL',exit_code:p.status,
 output_tail:(p.stdout||'').trim().split('\n').slice(-3).join('\n'),error_tail:(p.stderr||'').trim().split('\n').slice(-5).join('\n')});
}
const rac=suites[3];const racRun=runs[3];let perCase=[];
if(fs.existsSync(path.join(root,rac.report))){
 const report=read(rac.report),dataset=read(rac.dataset);
 const ids=new Set(dataset.cases.map(c=>c.id));
 const resultIds=new Set((report.results||[]).map(c=>c.id));
 if(racRun.status!=='PASS'||report.results?.length!==dataset.cases.length||
    resultIds.size!==ids.size||[...ids].some(id=>!resultIds.has(id))){
  racRun.status='REPORT_MISMATCH';
 }else{
  const byId=new Map(dataset.cases.map(c=>[c.id,c]));
  perCase=report.results.map(x=>{
   const original=byId.get(x.id);
   return {id:x.id,status:x.pass?'PASS':'FAIL',expected_positive:original.expected_diagnoses||[],
    expected_hypotheses:original.expected_hypotheses||[],expected_forbidden:original.forbidden_diagnoses||[],
    actual_diagnoses:x.diagnoses||[],actual_hypotheses:x.hypotheses||[],errors:x.errors||[],
    source_verification:'NOT_ASSESSED'};
  });
 }
}else{racRun.status='REPORT_MISSING';}
const faults=phase4.faults.map(f=>{
 const positive=perCase.filter(c=>c.expected_positive.includes(f.id));
 return {id:f.id,phase4_positive_scenarios:f.positive_scenarios.length,
  executed_positive_scenarios:positive.length,passing_positive_scenarios:positive.filter(c=>c.status==='PASS').length,
  failing_positive_scenarios:positive.filter(c=>c.status==='FAIL').length,
  independent_source_validation:'NOT_ASSESSED'};
});
const summary={faults:faults.length,phase4_scenarios:phase4.summary.cases,
 phase4_explicitly_linked:phase4.summary.cases_with_explicit_fault_expectations,
 suites_passed:runs.filter(s=>s.status==='PASS').length,suites_total:runs.length,
 per_case_results:perCase.length,per_case_pass:perCase.filter(c=>c.status==='PASS').length,
 per_case_fail:perCase.filter(c=>c.status==='FAIL').length,
 faults_with_passing_positive_execution:faults.filter(f=>f.passing_positive_scenarios>0).length,
 independently_verified_cases:0};
const data={schema_version:'1.0.0',summary,suites:runs,phase4_dataset_inventory:phase4.inventory,
 faults,per_case_results:perCase,
 methodology:'Phase 4 canonical fault expectation links plus actual execution of four suites; case-level mapping only for residential A/C deep suite.',
 caveats:['Suite-level PASS is not per-fault validation without individual assertion traceability.',
 'Passing internal expectations is not independent textbook/manufacturer verification.',
 'No diagnostic engine rules are modified.',
 'Other datasets are not yet linked to individual execution outcomes.',
 'Chapter 7 textbook answers take priority for equivalent textbook conditions after assumptions are checked.']};
const docs=path.join(root,'docs');fs.mkdirSync(docs,{recursive:true});
fs.writeFileSync(path.join(docs,'knowledge_coverage.json'),JSON.stringify(data,null,2)+'\n');
const lines=['# Knowledge Coverage — Consolidated Registry','',
 'Generated by `node tools/knowledge_coverage.mjs`. Do not edit manually.','',
 '## Summary','',...Object.entries(summary).map(([k,v])=>`- ${k}: ${v}`),'',
 '## Execution suites','','| Suite | Status |','|---|---|',...runs.map(s=>`| ${s.id} | ${s.status} |`),'',
 '## Fault coverage','','| Fault | Phase 4 positive scenarios | Executed positive | Passing | Failing | Independent verification |',
 '|---|---:|---:|---:|---:|---|',...faults.map(f=>`| ${f.id} | ${f.phase4_positive_scenarios} | ${f.executed_positive_scenarios} | ${f.passing_positive_scenarios} | ${f.failing_positive_scenarios} | ${f.independent_source_validation} |`),
 '','## Source priority and corrections','',
 'For textbook scenarios, preserve the textbook reference answer and compare equivalent operating conditions before correcting the brain. Correct reusable reasoning, not only test expectations. Keep equipment-specific manufacturer documentation in view when equipment differs from textbook assumptions.','',
 '## Limitations','',...data.caveats.map(x=>'- '+x)];
fs.writeFileSync(path.join(docs,'knowledge_coverage.md'),lines.join('\n')+'\n');
console.log(`KNOWLEDGE COVERAGE: ${summary.faults} faults; ${summary.phase4_scenarios} scenarios; ${summary.suites_passed}/${summary.suites_total} suites PASS; ${summary.per_case_results} case results; ${summary.per_case_pass} PASS; ${summary.per_case_fail} FAIL; ${summary.faults_with_passing_positive_execution} faults with passing positive cases; independent verification NOT ASSESSED`);
if(summary.suites_passed!==summary.suites_total||summary.per_case_fail)process.exitCode=1;
